#!/usr/bin/env python3
"""
Signs reader firmware for the bootloader (Bootloader/, design note
docs/design/0020-bootloader-and-signed-update.md).

  genkey  Creates the ECDSA P-256 signing key and writes its public half
          into Bootloader/boot_public_key.c. Refuses to overwrite a key.
  sign    Wraps an application .bin in the 256-byte image header and
          signs it: the result (.tlfw) is what Tools/fw_update.py sends.
  info    Prints an image header; with --key or --public-c it also
          checks the signature.

The header layout matches Firmware/Common/firmware_image.h.

KEEP THE PRIVATE KEY SAFE AND BACKED UP. Readers only accept images
signed with the key whose public half is in their bootloader; without
it, field updates stop and every reader needs SWD (and, with read
protection set, a mass erase) to get a new bootloader.

Requires:  python -m pip install cryptography
"""

import argparse
import hashlib
import os
import re
import struct
import sys

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils

MAGIC = 0x57464C54            # "TLFW"
HEADER_VERSION = 1
HEADER_SIZE = 256
SIGNED_SIZE = 128
STATE_PENDING = 0xFFFFFFFF
APP_BASE = 0x08004000

BOARDS = {
    "f429": {"id": 0x419, "max": 624 * 1024},
    "f411": {"id": 0x431, "max": 112 * 1024},
}

STATES = {
    0xFFFFFFFF: "PENDING",
    0x00000000: "INSTALLED",
    0x0000BAD1: "BAD_HEADER",
    0x0000BAD2: "BAD_HASH",
    0x0000BAD3: "BAD_SIGNATURE",
}

# Fixed part of the header, little-endian:
# magic, headerVersion, headerSize, boardId, loadAddress, imageSize,
# reserved0[3], version[32], imageSha256[32], reserved1[32]
HEADER_SIGNED = struct.Struct("<IHHIII12s32s32s32s")


def load_private_key(path):
    with open(path, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)


def public_xy(public_key):
    numbers = public_key.public_numbers()
    return numbers.x.to_bytes(32, "big") + numbers.y.to_bytes(32, "big")


def public_from_c(path):
    with open(path, "r", encoding="ascii") as f:
        values = re.findall(r"0x([0-9A-Fa-f]{2})", f.read())
    raw = bytes(int(v, 16) for v in values)
    if len(raw) != 64:
        raise SystemExit(f"{path}: expected 64 key bytes, found {len(raw)}")
    return ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), b"\x04" + raw)


def write_public_c(path, raw):
    lines = []
    for i in range(0, 64, 8):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in raw[i:i + 8]) + ",")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(
            "/*\n"
            " * boot_public_key.c\n"
            " *\n"
            " * Public half of the firmware signing key (ECDSA P-256, X || Y,\n"
            " * big-endian). Generated by Tools/fw_sign.py genkey: the bootloader\n"
            " * installs only images signed with the matching private key.\n"
            " */\n\n"
            "#include <stdint.h>\n\n"
            "const uint8_t g_bootPublicKey[64] =\n{\n"
            + "\n".join(lines) + "\n};\n"
        )


def cmd_genkey(args):
    if os.path.exists(args.key):
        raise SystemExit(f"{args.key} already exists; not overwriting a signing key")
    key = ec.generate_private_key(ec.SECP256R1())
    os.makedirs(os.path.dirname(os.path.abspath(args.key)), exist_ok=True)
    with open(args.key, "wb") as f:
        f.write(key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        ))
    write_public_c(args.public_c, public_xy(key.public_key()))
    print(f"private key: {args.key}  (back it up; never commit it)")
    print(f"public key:  {args.public_c}")


def cmd_sign(args):
    board = BOARDS[args.board]
    with open(args.input, "rb") as f:
        binary = f.read()
    if not binary:
        raise SystemExit("empty input")
    if len(binary) > board["max"]:
        raise SystemExit(f"{len(binary)} bytes exceeds the {board['max']}-byte application area")
    version = args.version.encode("ascii")
    if len(version) > 31:
        raise SystemExit("version text longer than 31 characters")

    # The vector table must point into the application area, or the
    # bootloader would refuse to start it.
    stack, entry = struct.unpack_from("<II", binary, 0)
    if not (APP_BASE <= (entry & ~1) < APP_BASE + board["max"]) or not entry & 1:
        raise SystemExit(f"reset vector 0x{entry:08X} is not in the application area: "
                         "was the .bin linked for 0x08004000?")

    signed = HEADER_SIGNED.pack(
        MAGIC, HEADER_VERSION, HEADER_SIZE, board["id"], APP_BASE, len(binary),
        bytes(12), version.ljust(32, b"\0"), hashlib.sha256(binary).digest(), bytes(32),
    )
    assert len(signed) == SIGNED_SIZE

    key = load_private_key(args.key)
    r, s = utils.decode_dss_signature(key.sign(signed, ec.ECDSA(hashes.SHA256())))
    signature = r.to_bytes(32, "big") + s.to_bytes(32, "big")

    tail = struct.pack("<I", STATE_PENDING) + b"\xff" * 60
    header = signed + signature + tail
    assert len(header) == HEADER_SIZE

    with open(args.output, "wb") as f:
        f.write(header + binary)
    print(f"{args.output}: {args.board} {args.version}, {len(binary)} bytes, signed")


def cmd_info(args):
    with open(args.image, "rb") as f:
        data = f.read()
    if len(data) < HEADER_SIZE:
        raise SystemExit("file shorter than the header")
    (magic, hver, hsize, board_id, load, size, _r0, version, digest, _r1) = \
        HEADER_SIGNED.unpack_from(data, 0)
    state = struct.unpack_from("<I", data, 0xC0)[0]
    board = next((n for n, b in BOARDS.items() if b["id"] == board_id), f"0x{board_id:X}")
    print(f"magic        {'ok' if magic == MAGIC else f'BAD 0x{magic:08X}'}")
    print(f"format       {hver}, header {hsize} bytes")
    print(f"board        {board}")
    print(f"load address 0x{load:08X}")
    print(f"version      {version.rstrip(bytes(1)).decode('ascii', 'replace')}")
    print(f"size         {size}")
    print(f"state        {STATES.get(state, f'0x{state:08X}')}")
    body = data[HEADER_SIZE:HEADER_SIZE + size]
    print(f"sha-256      {'ok' if hashlib.sha256(body).digest() == digest and len(body) == size else 'MISMATCH'}")

    public_key = None
    if args.key:
        public_key = load_private_key(args.key).public_key()
    elif args.public_c:
        public_key = public_from_c(args.public_c)
    if public_key is not None:
        sig = data[0x80:0xC0]
        der = utils.encode_dss_signature(int.from_bytes(sig[:32], "big"),
                                         int.from_bytes(sig[32:], "big"))
        try:
            public_key.verify(der, data[:SIGNED_SIZE], ec.ECDSA(hashes.SHA256()))
            print("signature    ok")
        except InvalidSignature:
            print("signature    BAD")
            return 1
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("genkey", help="create the signing key")
    p.add_argument("--key", default="keys/fw_signing_key.pem")
    p.add_argument("--public-c", default="Bootloader/boot_public_key.c")
    p.set_defaults(func=cmd_genkey)

    p = sub.add_parser("sign", help="sign an application .bin")
    p.add_argument("--key", default="keys/fw_signing_key.pem")
    p.add_argument("--board", choices=sorted(BOARDS), required=True)
    p.add_argument("--version", required=True, help='shown by FW_STATUS, e.g. "v0.11.0"')
    p.add_argument("input")
    p.add_argument("output")
    p.set_defaults(func=cmd_sign)

    p = sub.add_parser("info", help="print and check an image")
    p.add_argument("image")
    p.add_argument("--key", help="check the signature with this private key")
    p.add_argument("--public-c", help="check the signature with boot_public_key.c")
    p.set_defaults(func=cmd_info)

    args = parser.parse_args()
    return args.func(args) or 0


if __name__ == "__main__":
    sys.exit(main())
